CREATE TABLE marcas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL REFERENCES empresas(id),
    nome VARCHAR(100) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_marca_id_empresa UNIQUE (id, empresa_id),
    CONSTRAINT ck_marca_nome CHECK (nome = btrim(nome) AND length(nome) > 0)
);
CREATE UNIQUE INDEX uk_marca_nome_empresa ON marcas (empresa_id, lower(nome));

