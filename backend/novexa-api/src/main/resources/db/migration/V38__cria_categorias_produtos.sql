CREATE TABLE categorias_produtos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL REFERENCES empresas(id),
    nome VARCHAR(100) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_categoria_produto_id_empresa UNIQUE (id, empresa_id),
    CONSTRAINT ck_categoria_produto_nome CHECK (nome = btrim(nome) AND length(nome) > 0)
);
CREATE UNIQUE INDEX uk_categoria_produto_nome_empresa ON categorias_produtos (empresa_id, lower(nome));

CREATE TABLE subcategorias_produtos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL REFERENCES empresas(id),
    categoria_id BIGINT NOT NULL,
    nome VARCHAR(100) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_subcategoria_categoria_empresa FOREIGN KEY (categoria_id, empresa_id)
        REFERENCES categorias_produtos(id, empresa_id),
    CONSTRAINT ck_subcategoria_produto_nome CHECK (nome = btrim(nome) AND length(nome) > 0)
);
CREATE UNIQUE INDEX uk_subcategoria_produto_nome_empresa ON subcategorias_produtos (empresa_id, lower(nome));
CREATE INDEX idx_subcategoria_categoria_empresa ON subcategorias_produtos (empresa_id, categoria_id);
